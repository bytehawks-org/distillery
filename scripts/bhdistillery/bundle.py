"""The Distillery -> Shaker contract: <bundle>/{manifest.json, rosetta.map, runtime.spec, assets/}.

rosetta.map   parameters (env, CLI, aliases, config file keys), see Shaker docs/ROSETTA.md
runtime.spec  user, directories, templates, hooks, run command, healthcheck, persistence
manifest.json identity and provenance of the build (manifest.env: flat copy for Shaker)
assets/       templates and hooks copied from distillery/assets/<package>/

Both text files are line oriented with '|' as separator so Shaker can read them in pure bash.
"""

import json
import os
import re
import shutil
import time
from pathlib import Path

from . import BUNDLE_SCHEMA, __version__
from .templates import resolve_dict_templates

RUNTIME_TYPES = ("string", "secret", "int", "uint", "port", "bool", "path")
ENV_NAME_RE = re.compile(r"^[A-Z][A-Z0-9_]*$")
HOOK_STAGES = ("pre_init", "first_init", "post_init")
FORBIDDEN = ("|", "\n")


class BundleError(ValueError):
    pass


def _check(value, where):
    text = str(value)
    if any(c in text for c in FORBIDDEN):
        raise BundleError(f"{where}: '|' and newlines are not allowed in '{text[:40]}'")
    return text


def _scalar(value):
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    return str(value)


def env_prefix(package_name):
    return "BH_" + package_name.upper().replace("-", "_") + "_"


def rosetta_lines(unit):
    runtime = resolve_dict_templates(unit.package.get("runtime", {}), unit.context)
    prefix = env_prefix(unit.name)
    lines = ["# Generated by Distillery - do not edit",
             "# env|type|default|flags|aliases|file_key|cli|native_env|description"]
    seen = set()

    for item in runtime.get("env", []):
        name = item.get("name", "")
        if not ENV_NAME_RE.match(name) or not name.startswith(prefix):
            raise BundleError(f"runtime.env: '{name}' must start with {prefix}")
        if name in seen:
            raise BundleError(f"runtime.env: duplicate '{name}'")
        seen.add(name)

        vtype = str(item.get("type", "string"))
        if vtype not in RUNTIME_TYPES and not (vtype.startswith("enum:") and len(vtype) > 5):
            raise BundleError(f"runtime.env {name}: invalid type '{vtype}'")

        fields = [name, vtype, _scalar(item.get("default")),
                  "required" if item.get("required") else "",
                  ",".join(item.get("aliases", [])), item.get("file_key", ""),
                  item.get("cli", ""), item.get("native_env", ""), item.get("description", "")]
        lines.append("|".join(_check(f, f"runtime.env {name}") for f in fields))

    return lines


def spec_lines(unit):
    """runtime.spec records:

      user|name|uid|gid|home
      dir|path|mode|owner       (owner = uid:gid, created at `shaker install`)
      persist|path|volume       (seeded from path on first start, then served from volume)
      template|src|dest|mode    (src relative to the bundle assets/, rendered at `shaker init`)
      hook|stage|directory      (stage: pre_init, first_init, post_init)
      run|argv0|argv1|...       (${VAR} expanded by Shaker from the resolved parameters)
      stopsignal|TERM
      health|tcp|host|port      or health|cmd|argv0|argv1|...
      pidfile|path
      requires|command          (tools that must exist at `shaker verify`)
      mutable|path              (rewritten by the runtime on purpose: skipped by `verify --files`)
    """
    runtime = resolve_dict_templates(unit.package.get("runtime", {}), unit.context)
    lines = ["# Generated by Distillery - do not edit"]

    user = runtime.get("user")
    if user:
        lines.append("|".join(_check(f, "runtime.user") for f in (
            "user", user["name"], _scalar(user.get("uid")), _scalar(user.get("gid", 0)), user.get("home", ""))))

    for d in runtime.get("dirs", []):
        lines.append("|".join(_check(f, "runtime.dirs") for f in (
            "dir", d["path"], d.get("mode", "0755"), d.get("owner", ""))))

    for p in runtime.get("persistence", []):
        lines.append("|".join(_check(f, "runtime.persistence") for f in ("persist", p["path"], p["volume"])))

    for t in runtime.get("templates", []):
        lines.append("|".join(_check(f, "runtime.templates") for f in (
            "template", t["src"], t["dest"], t.get("mode", "0644"))))

    for stage, directory in runtime.get("hooks", {}).items():
        if stage not in HOOK_STAGES:
            raise BundleError(f"runtime.hooks: unknown stage '{stage}' (use {', '.join(HOOK_STAGES)})")
        lines.append("|".join(_check(f, "runtime.hooks") for f in ("hook", stage, directory)))

    if "run" in runtime:
        argv = runtime["run"]["command"]
        if not isinstance(argv, list) or not argv:
            raise BundleError("runtime.run.command must be a non-empty list (argv, no shell)")
        lines.append("|".join(["run"] + [_check(a, "runtime.run") for a in argv]))
        lines.append("stopsignal|" + _check(runtime["run"].get("stop_signal", "TERM"), "runtime.run"))
        if runtime["run"].get("pidfile"):
            lines.append("pidfile|" + _check(runtime["run"]["pidfile"], "runtime.run"))

    health = runtime.get("healthcheck")
    if health:
        if "tcp" in health:
            lines.append("|".join(_check(f, "runtime.healthcheck") for f in (
                "health", "tcp", health["tcp"].get("host", "127.0.0.1"), health["tcp"]["port"])))
        elif "command" in health:
            lines.append("|".join(["health", "cmd"] + [_check(a, "runtime.healthcheck") for a in health["command"]]))
        else:
            raise BundleError("runtime.healthcheck needs 'tcp' or 'command'")

    for tool in runtime.get("requires", []):
        lines.append("requires|" + _check(tool, "runtime.requires"))

    for path in runtime.get("mutable", []):
        lines.append("mutable|" + _check(path, "runtime.mutable"))

    return lines


def manifest(unit, built=False, toolchain=None, built_epoch=None):
    data = {
        "schema": BUNDLE_SCHEMA,
        "generator": f"distillery/{__version__}",
        "package": unit.name,
        "variant": unit.variant,
        "tag": unit.tag,
        "version": str(unit.variant_data["full_version"]),
        "prefix": unit.prefix,
        "arch": unit.context["arch"],
        "libc": unit.context["libc"],
        "linkage": unit.context["linkage"],
        "source": (unit.context["git"].get("release_download_url_template", "")
                   or f"{unit.context['git'].get('repo', '')}#{unit.context['git'].get('ref_template', '')}"),
        "source_sha256": unit.variant_data.get("sha256", ""),
        "source_commit": unit.variant_data.get("commit", ""),
        "recipe_sha256": unit.recipe_sha256,
        "depends": [{"package": d.name, "variant": d.variant, "version": str(d.variant_data["full_version"]),
                     "recipe_sha256": d.recipe_sha256} for d in unit.depends],
    }
    if built:
        epoch = int(built_epoch if built_epoch is not None else os.environ.get("SOURCE_DATE_EPOCH", time.time()))
        data["built_at"] = time.strftime("%Y-%m-%dT%H:%M:%SZ", time.gmtime(epoch))
        if toolchain:
            data["toolchain"] = toolchain
    return data


def manifest_env(data):
    """Flat KEY=VALUE view of the manifest: what Shaker exposes as BH_PKG_* to templates and hooks."""
    return "".join(f"{key}={value}\n" for key, value in (
        ("BH_PKG_NAME", data["package"]), ("BH_PKG_VERSION", data["version"]),
        ("BH_PKG_VARIANT", data["variant"]), ("BH_PKG_PREFIX", data["prefix"]),
        ("BH_PKG_RECIPE", data["recipe_sha256"]),
        ("BH_PKG_ARCH", data.get("arch", "")), ("BH_PKG_LIBC", data.get("libc", "")),
        ("BH_PKG_LINKAGE", data.get("linkage", "")),
        # direct dependencies, "<package>=<recipe sha256>" separated by spaces: what `shaker up` orders and checks
        ("BH_PKG_DEPENDS", " ".join(f"{d['package']}={d['recipe_sha256']}" for d in data.get("depends", [])))) if value != "")


def emit(unit, assets_root, out_dir=None, built=False, toolchain=None, built_epoch=None):
    """Write the bundle of a unit and return its directory."""
    out = Path(out_dir) if out_dir else unit.bundle_dir
    out.mkdir(parents=True, exist_ok=True)

    (out / "rosetta.map").write_text("\n".join(rosetta_lines(unit)) + "\n")
    (out / "runtime.spec").write_text("\n".join(spec_lines(unit)) + "\n")
    data = manifest(unit, built, toolchain, built_epoch)
    (out / "manifest.json").write_text(json.dumps(data, indent=2, sort_keys=True) + "\n")
    (out / "manifest.env").write_text(manifest_env(data))

    assets = Path(assets_root) / unit.name
    if assets.is_dir():
        target = out / "assets"
        if target.exists():
            shutil.rmtree(target)
        shutil.copytree(assets, target)

    install_hooks(unit, assets_root)
    return out


SEAL = "bundle.sha256"


def seal(bundle_dir, config=None, log=print):
    """Write `bundle.sha256` (sha256sum format, paths relative to the bundle directory) over the contract files, the
    assets and `files.sha256` when present, and sign it (`bundle.sha256.asc`) if a signing key is configured.

    The signature covers `files.sha256`, which in turn lists every installed file: one signature authenticates the
    whole unit for a consumer (Shaker `verify`) that has only the installed tree. Returns the files written."""
    from .fetch import sha256_file
    from . import signature

    bundle_dir = Path(bundle_dir)
    names = [n for n in ("manifest.json", "manifest.env", "rosetta.map", "runtime.spec", "files.sha256")
             if (bundle_dir / n).is_file()]
    names += sorted(p.relative_to(bundle_dir).as_posix() for p in (bundle_dir / "assets").rglob("*") if p.is_file()) \
        if (bundle_dir / "assets").is_dir() else []
    digest = bundle_dir / SEAL
    digest.write_text("".join(f"{sha256_file(bundle_dir / n)}  {n}\n" for n in names))
    written = [digest]
    if config is not None and signature.signing_settings(config)["key"]:
        written.append(signature.sign_artifact(digest, config, log))
    else:
        (bundle_dir / f"{SEAL}.asc").unlink(missing_ok=True)          # never leave the signature of an older digest
    return [p for p in written if p]


def install_hooks(unit, assets_root):
    """Copy assets/<package>/hooks/<stage>/* into the hook directory the runtime declares for that stage.

    The files keep their relative layout and get the execute bit; the directory is the one Shaker runs.
    Done at emit time so the hooks are part of the unit (artifact, recipe-tied) without a `post` stage."""
    runtime = resolve_dict_templates(unit.package.get("runtime", {}), unit.context)
    for stage, directory in runtime.get("hooks", {}).items():
        source = Path(assets_root) / unit.name / "hooks" / stage
        if not source.is_dir():
            continue
        target = Path(directory)
        target.mkdir(parents=True, exist_ok=True)
        for hook in sorted(p for p in source.iterdir() if p.is_file()):
            shutil.copy2(hook, target / hook.name)
            (target / hook.name).chmod(0o755)


def is_up_to_date(unit):
    """True when an installed bundle matches the current recipe (nothing to rebuild)."""
    path = unit.bundle_dir / "manifest.json"
    try:
        current = json.loads(path.read_text())
    except (OSError, ValueError):
        return False
    return current.get("recipe_sha256") == unit.recipe_sha256 and current.get("built_at") is not None
