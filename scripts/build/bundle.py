"""
Make dynamically linked (musl) programs relocatable and host-independent.

For every dynamic ELF in the tree we copy the shared libraries it needs plus the
dynamic loader into ``lib/bundled`` and replace each executable ``X`` by a tiny
shell wrapper that starts ``X.bin`` through the bundled loader:

    exec lib/bundled/ld-musl-x86_64.so.1 --library-path lib/bundled:lib bin/X.bin "$@"

The result runs on any Linux of the same architecture (glibc or musl hosts),
wherever it is extracted.
"""

import os
import shutil
import stat
import subprocess
from pathlib import Path
from typing import Dict, Set

from scripts.build.verify import iter_files, read_elf
from scripts.core.exceptions import BuildError

BUNDLE_DIR = "lib/bundled"
WRAPPER = """#!/bin/sh
# Generated by bytehawks-distillery: runs {name}.bin with its bundled loader and libraries.
self="$0"
while [ -h "$self" ]; do
  link=$(readlink "$self")
  case "$link" in /*) self="$link" ;; *) self="$(dirname "$self")/$link" ;; esac
done
here=$(cd "$(dirname "$self")" && pwd -P)
root="$here/{up}"
exec "$root/{bundle}/{loader}" --library-path "$root/{bundle}:$root/lib" "$here/{name}.bin" "$@"
"""


def _lib_dirs(root: Path) -> str:
    dirs: Set[str] = set()
    for p in iter_files(root):
        if p.suffix == ".so" or ".so." in p.name:
            dirs.add(str(p.parent))
    return ":".join(sorted(dirs))


def _ldd(path: Path, env: Dict[str, str]) -> Set[Path]:
    proc = subprocess.run(["ldd", str(path)], capture_output=True, text=True, env=env)
    found: Set[Path] = set()
    for line in proc.stdout.splitlines():
        line = line.strip()
        if "not found" in line:
            raise BuildError(f"bundle: unresolved library for {path.name}: {line}")
        if "=>" in line:
            target = line.split("=>", 1)[1].split("(", 1)[0].strip()
            if target.startswith("/"):
                found.add(Path(target))
    return found


def bundle_runtime(root: Path) -> None:
    """Bundle loader + libraries and wrap all dynamic executables under ``root``."""
    elfs = [(p, read_elf(p)) for p in iter_files(root)]
    elfs = [(p, i) for p, i in elfs if i is not None]
    dynamic = [(p, i) for p, i in elfs if i.has_dynamic or i.has_interp]
    if not dynamic:
        return

    loaders = {i.interp for _p, i in dynamic if i.interp}
    if len(loaders) > 1:
        raise BuildError(f"bundle: multiple dynamic loaders in tree: {sorted(loaders)}")
    loader_path = Path(loaders.pop()) if loaders else None
    if loader_path is None or not loader_path.exists():
        raise BuildError("bundle: dynamic loader not found on the build host")

    bundle = root / BUNDLE_DIR
    bundle.mkdir(parents=True, exist_ok=True)

    env = dict(os.environ, LD_LIBRARY_PATH=_lib_dirs(root))
    needed: Set[Path] = set()
    for p, _i in dynamic:
        needed |= _ldd(p, env)

    root_resolved = root.resolve()
    for lib in sorted(needed):
        real = lib.resolve()
        if str(real).startswith(str(root_resolved)):
            continue
        if real == loader_path.resolve():
            continue
        shutil.copy2(real, bundle / lib.name, follow_symlinks=True)

    loader_name = loader_path.name
    shutil.copy2(loader_path.resolve(), bundle / loader_name)
    # musl: the loader is libc itself; make its soname resolvable from the bundle
    if loader_name.startswith("ld-musl-"):
        alias = bundle / ("libc.musl-" + loader_name[len("ld-musl-"):])
        alias.unlink(missing_ok=True)
        alias.symlink_to(loader_name)

    for p, info in dynamic:
        is_exe = os.access(p, os.X_OK) and not (p.suffix == ".so" or ".so." in p.name)
        if not is_exe or not info.has_interp:
            continue
        mode = stat.S_IMODE(p.stat().st_mode)
        real_bin = p.with_name(p.name + ".bin")
        p.rename(real_bin)
        depth = len(p.parent.relative_to(root).parts)
        p.write_text(WRAPPER.format(name=p.name, up="/".join([".."] * depth) if depth else ".",
                                    bundle=BUNDLE_DIR, loader=loader_name))
        p.chmod(mode | 0o111)
        real_bin.chmod(mode)
